def load(name):
    text = (DIR / name).read_text(encoding="utf-8")
    text = re.sub(r"^export default\s*", "", text.strip()).rstrip(";")
    return json.loads(text)


def dump(obj):
    return "export default " + json.dumps(obj, ensure_ascii=False, indent=2) + "\n"


def apply_frags(key, frags):
    s = key
    for zh, loc in sorted(frags, key=lambda x: -len(x[0])):
        if zh and zh in s:
            s = s.replace(zh, loc)
    return s


def fill(src, exact, frags, script_re):
    out = {}
    leftover = []
    for k in src.keys():
        if k in exact:
            out[k] = exact[k]
            continue
        val = apply_frags(k, frags)
        if HAN.search(val):
            leftover.append(k)
        out[k] = val
    return out, leftover


